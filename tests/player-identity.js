const assert=require('node:assert/strict');
const {loadGame}=require('./game-harness');
const {DS}=loadGame();
DS.UI.render=()=>{};
DS.Meta.newGame();
assert.throws(()=>DS.State.newRun(),/Identify the player/);
assert.equal(DS.State.load(),false,'resume is gated before any save is read');
assert.throws(()=>DS.PlayerIdentity.set({type:'human',name:'  '}),/name/);
assert.throws(()=>DS.PlayerIdentity.set({type:'ai',provider:'OpenAI',model:'unknown',modelVersion:'unknown'}),/effort/);
DS.PlayerIdentity.set({type:'human',name:'Test Player'});
DS.State.newRun();
let start=DS.Telemetry.archive().events.find(e=>e.type==='run.start');
assert.equal(start.actor.name,'Test Player');
DS.PlayerIdentity.set({type:'ai',provider:'OpenAI',model:'unknown',modelVersion:'unknown',effort:'unknown'});
DS.Telemetry.record('ai.test');
const event=DS.Telemetry.archive().events.find(e=>e.type==='ai.test');
assert.equal(event.actor.model,'unknown');
assert.equal(event.actor.effort,'unknown');
DS.PlayerIdentity.set({type:'scripted',policy:'cautious',policyVersion:'1'});
DS.Telemetry.record('script.test');
const script=DS.Telemetry.archive().events.find(e=>e.type==='script.test');
assert.equal(script.actor.effort,'not applicable');
assert.equal(script.actor.model,undefined,'scripted policy must not pretend to be an AI model');
assert.equal(start.actor.name,'Test Player','prior attribution stays immutable after actor changes');
console.log('PASS: unidentified start/resume blocked; human name required; AI fields explicit; unknown preserved; scripted effort not applicable; historical actors immutable');
